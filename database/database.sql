-- 3. CREATE TABLES WITH CONSTRAINTS
-- ---------------------------------------------------------------------

-- TABLE 1: USERS
CREATE TABLE USERS (
    USER_ID     NUMBER PRIMARY KEY,
    USERNAME    VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD    VARCHAR2(100) NOT NULL,
    ROLE        VARCHAR2(20) NOT NULL,
    FULL_NAME   VARCHAR2(100),
    EMAIL       VARCHAR2(100),
    CONSTRAINT CHK_USER_ROLE CHECK (ROLE IN ('ADMIN', 'ORGANIZER'))
);

-- TABLE 2: ORGANIZER
CREATE TABLE ORGANIZER (
    ORGANIZER_ID NUMBER PRIMARY KEY,
    NAME         VARCHAR2(100) NOT NULL,
    EMAIL        VARCHAR2(100) NOT NULL UNIQUE,
    PHONE        VARCHAR2(15),
    DEPARTMENT   VARCHAR2(100),
    USERNAME     VARCHAR2(50)
);

-- TABLE 3: VENUE
CREATE TABLE VENUE (
    VENUE_ID    NUMBER PRIMARY KEY,
    VENUE_NAME  VARCHAR2(100) NOT NULL,
    LOCATION    VARCHAR2(200),
    CAPACITY    NUMBER NOT NULL,
    AVAILABLE   VARCHAR2(5) DEFAULT 'YES' NOT NULL,
    CONSTRAINT CHK_VENUE_CAPACITY CHECK (CAPACITY > 0),
    CONSTRAINT CHK_VENUE_AVAILABLE CHECK (AVAILABLE IN ('YES', 'NO'))
);

-- TABLE 4: EVENT
CREATE TABLE EVENT (
    EVENT_ID          NUMBER PRIMARY KEY,
    EVENT_NAME        VARCHAR2(150) NOT NULL,
    EVENT_TYPE        VARCHAR2(50) NOT NULL,
    DESCRIPTION       VARCHAR2(500),
    EVENT_DATE        DATE NOT NULL,
    START_TIME        VARCHAR2(20),
    END_TIME          VARCHAR2(20),
    ORGANIZER_ID      NUMBER NOT NULL,
    VENUE_ID          NUMBER NOT NULL,
    MAX_CAPACITY      NUMBER NOT NULL,
    REGISTRATION_FEE  NUMBER(10,2) DEFAULT 0,
    STATUS            VARCHAR2(20) DEFAULT 'UPCOMING' NOT NULL,
    CONSTRAINT FK_EVENT_ORGANIZER FOREIGN KEY (ORGANIZER_ID) REFERENCES ORGANIZER(ORGANIZER_ID),
    CONSTRAINT FK_EVENT_VENUE FOREIGN KEY (VENUE_ID) REFERENCES VENUE(VENUE_ID),
    CONSTRAINT CHK_EVENT_CAPACITY CHECK (MAX_CAPACITY > 0),
    CONSTRAINT CHK_EVENT_FEE CHECK (REGISTRATION_FEE >= 0),
    CONSTRAINT CHK_EVENT_STATUS CHECK (STATUS IN ('UPCOMING', 'ONGOING', 'COMPLETED', 'CANCELLED'))
);

-- TABLE 5: PARTICIPANT
CREATE TABLE PARTICIPANT (
    PARTICIPANT_ID NUMBER PRIMARY KEY,
    NAME           VARCHAR2(100) NOT NULL,
    EMAIL          VARCHAR2(100) NOT NULL UNIQUE,
    PHONE          VARCHAR2(15),
    COLLEGE        VARCHAR2(150),
    DEPARTMENT     VARCHAR2(100)
);

-- TABLE 6: REGISTRATION
CREATE TABLE REGISTRATION (
    REGISTRATION_ID   NUMBER PRIMARY KEY,
    EVENT_ID          NUMBER NOT NULL,
    PARTICIPANT_ID    NUMBER NOT NULL,
    REGISTRATION_DATE DATE DEFAULT SYSDATE NOT NULL,
    STATUS            VARCHAR2(20) DEFAULT 'REGISTERED' NOT NULL,
    CONSTRAINT FK_REG_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENT(EVENT_ID),
    CONSTRAINT FK_REG_PARTICIPANT FOREIGN KEY (PARTICIPANT_ID) REFERENCES PARTICIPANT(PARTICIPANT_ID),
    CONSTRAINT UQ_EVENT_PARTICIPANT UNIQUE (EVENT_ID, PARTICIPANT_ID),
    CONSTRAINT CHK_REG_STATUS CHECK (STATUS IN ('REGISTERED', 'CANCELLED', 'ATTENDED'))
);

